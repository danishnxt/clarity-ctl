"""Generated views: EPOCH.md and the terminal status block.

Nothing here reads state from disk; it is handed model objects and returns text.

There is deliberately no STATUS.md renderer. The status view mixes the worklog with
leases and git ahead/behind — machine-local facts that change with no command running
— so a committed file could only ever be wrong about them. `clarity-ctl status` composes
it on every run instead, which is the one place all three inputs are live.
"""

from __future__ import annotations

import shutil
import sys
import textwrap
import unicodedata
from datetime import datetime

from .model import CLOSED, FUTURE, IN_FLIGHT, Item, Objectives

# Wrapped here, not by the terminal, so zooming or resizing never re-flows the output.
# Capped rather than fixed: a terminal narrower than the cap would wrap it again itself,
# which is the ugliness we're avoiding. Piped output ignores the terminal entirely.
MAX_WIDTH = 120
# Closed and Dropped show this many of their most recent; the rest are a flag away.
# The outcome is the point of a closed row, so the list is cut rather than the rows.
CLOSED_LIMIT = 15


def width() -> int:
    if not sys.stdout.isatty():
        return MAX_WIDTH  # stable for files and pipes
    return max(48, min(MAX_WIDTH, shutil.get_terminal_size((MAX_WIDTH, 24)).columns - 1))

MARK = "<!-- GENERATED by clarity — edit config.yaml or use clarity commands -->"
EPOCH_MARK_END = "<!-- /GENERATED — write your own notes below this line -->"

# Single-width glyphs on purpose: emoji are double-width in most terminals and would
# push every border after them out of true, differently per font.
_GLYPH = {
    "idea": "·",
    "active": "▸",
    "done": "✓",
    "dropped": "✗",
}


def _wrap(text: str, first: str, rest: str, cols: int) -> list[str]:
    return textwrap.wrap(text, width=cols, initial_indent=first, subsequent_indent=rest,
                         break_long_words=False, break_on_hyphens=False) or [first.rstrip()]



def note_age(item: Item) -> str | None:
    """How long the record has been standing still, for an epoch in flight.

    This exists because of a real failure: a session reversed the scope of its own
    epoch, tested it, had the result reviewed and rewrote it three times without
    writing one note, because every turn felt mid-task and a note was never the
    thing just asked for. Nothing in the view said so. Now it does — `status` is
    what an agent reads first, so it is where the nag belongs.
    """
    if item.status not in IN_FLIGHT or not item.notes:
        return None
    latest = max(n.at for n in item.notes)
    try:
        when = datetime.fromisoformat(latest)
    except ValueError:
        return None
    # A pre-timestamp note is a bare date, which parses as midnight — so its age
    # is coarse rather than absent. Better a day-granular nag on an old worklog
    # than silence on exactly the projects most likely to have gone quiet.
    minutes = int((datetime.now() - when).total_seconds() // 60)
    if minutes < 90:
        return None          # still warm; saying anything here is just noise
    if minutes < 60 * 24:
        return f"last note {minutes // 60}h ago"
    return f"last note {minutes // 1440}d ago"


def _landed(marks: dict[str, str] | None) -> str | None:
    """One word when every repo agrees, else one per repo — never a summary that hides a repo.

    unknown is left to --json: on an old worklog it marks nearly every early epoch,
    and a mark on everything is a mark on nothing."""
    marks = {repo: m for repo, m in (marks or {}).items() if m != "unknown"}
    if not marks:
        return None
    words = {"merged": "✅ merged", "unmerged": "❌ not merged"}
    if len(set(marks.values())) == 1:
        return words[next(iter(marks.values()))]
    return ", ".join(f"{repo}: {words[m]}" for repo, m in marks.items())


def _cell(item: Item, leases: dict | None, stale: dict | None,
          marks: dict | None) -> list[str]:
    """What goes in an item's main cell, one paragraph each: name, then detail.

    Name and outcome are tagged ONE_LINE: they are cut to a line, because an old
    sentence-length name would otherwise make every row a paragraph. Nothing you
    act on — folder, lease, warnings — is ever cut. `show <id>` has the whole text.
    """
    paras = [ONE_LINE + item.name]
    if item.status in CLOSED and item.outcome:
        paras.append(ONE_LINE + f"outcome: {item.outcome}")
    elif item.folder:
        paras.append(item.folder)
    held = (leases or {}).get(item.id)
    if held:
        # the age is the whole judgement: nothing expires, so you decide if it's stale
        who = f"{held.get('owner', '?')}@{held.get('host', '?')}"
        since = held.get("age")
        paras.append(f"held by {who}{', ' + since if since else ''}")
    mark = _landed(marks)
    if item.status in CLOSED and mark and ":" in mark:
        paras.append(f"landed: {mark}")  # the column says "mixed"; this says which
    quiet = note_age(item)
    if quiet:
        # about the record, not about where the work lives — so not on the folder line
        paras.append(f"⚠ {quiet} — clarity-ctl note {item.id} \"...\"")
    if item.status in IN_FLIGHT and marks and set(marks.values()) == {"merged"}:
        # only this one: unmerged is every epoch in flight, so saying it is noise
        paras.append(f"✓ its work is in its base — clarity-ctl epoch close {item.id} \"...\"")
    for trail in (stale or {}).get(item.id, []):
        # the base moving under an epoch is the thing you want to notice
        paras.append(f"⚠ {trail}")
    return paras


def _dw(text: str) -> int:
    """Columns `text` takes in a terminal: an emoji or CJK character takes two.

    len() counts it as one, which is how a ✅ pushes every border after it out."""
    return sum(0 if unicodedata.combining(c) or c == "\ufe0f" else
               2 if unicodedata.east_asian_width(c) in "WF" else 1 for c in text)


def _table(header: list[list[str]], rows: list[list[list[str]]], widths: list[int],
           right: set[int] = frozenset(), breaks: set[int] | None = None) -> list[str]:
    """Boxed rows, every cell already wrapped to its width; a rule before each row,
    or only before the rows in `breaks`.

    Hand-rolled rather than a library: the rest of status wraps by hand already,
    and a dependency for some box-drawing is weight every install would carry.
    """
    def rule(left: str, mid: str, end: str) -> str:
        return left + mid.join("─" * (w + 2) for w in widths) + end

    def row(cells: list[list[str]]) -> list[str]:
        out = []
        for k in range(max(len(c) for c in cells)):
            parts = []
            for col, (cell, w) in enumerate(zip(cells, widths)):
                text = cell[k] if k < len(cell) else ""
                pad = " " * max(0, w - _dw(text))
                parts.append(f" {pad}{text} " if col in right else f" {text}{pad} ")
            out.append("│" + "│".join(parts) + "│")
        return out

    out = [rule("┌", "┬", "┐"), *row(header)]
    for n, cells in enumerate(rows):
        if breaks is None or n in breaks:
            out.append(rule("├", "┼", "┤"))
        out += row(cells)
    return out + [rule("└", "┴", "┘")]


ONE_LINE = "\x00"  # marks a paragraph _fill cuts to one line rather than wraps


def _fill(paras: list[str], w: int) -> tuple[list[str], bool]:
    """Wrapped to the cell; True if a ONE_LINE paragraph had to be cut."""
    out, cut = [], False
    for p in paras:
        one = p.startswith(ONE_LINE)
        # long words break too: a path wider than the cell would push the border out
        lines = textwrap.wrap(p.lstrip(ONE_LINE), width=w, break_on_hyphens=False) or [""]
        if one and len(lines) > 1:
            first = lines[0]
            if len(first) > w - 2:
                first = first[:w - 2].rsplit(" ", 1)[0] if " " in first[:w - 2] else first[:w - 2]
            lines, cut = [first + " …"], True
        out += lines
    return out, cut


GROUPS = {
    "Active": IN_FLIGHT,
    "Up next": FUTURE,
    # Closed is what you finished; dropped work gets its own group, so scanning
    # what shipped is never interleaved with what you gave up on.
    "Closed": {"done"},
    "Dropped": {"dropped"},
}


def _groups(items: list[Item], groups: list[tuple[str, set]], cols: int,
            leases: dict | None, stale: dict | None, landed: dict | None,
            oldest_first: bool, limit: int) -> tuple[list[str], bool]:
    """One titled table per group. True as well if any name or outcome was cut."""
    out: list[str] = []
    cut_any = False
    for title, statuses in groups:
        chosen = [i for i in items if i.status in statuses]
        # closed_seq is exact where it exists; a project that predates it falls back to
        # the date, which is how these read before, so old worklogs keep their order.
        chosen.sort(key=lambda i: (i.closed_seq or 0, i.ended or i.created or "", i.id),
                    reverse=True)
        total, hidden = len(chosen), 0
        if statuses <= CLOSED and limit > 0 and len(chosen) > limit:
            # the most recent, whichever way they are then read
            hidden = len(chosen) - limit
            chosen = chosen[:limit]
        if oldest_first:
            chosen.reverse()
        out.append(f"{title} ({total})")  # the whole count, even when the list is cut
        if not chosen:
            out += ["  —", ""]
            continue
        # landed only where something can have landed: a closed epoch's work
        landed_col = title == "Closed"
        widths = [1, 3, 0] + ([12] if landed_col else [])
        widths[2] = cols - sum(widths) - 3 * len(widths) - 1  # borders and padding
        rows = []
        for item in chosen:
            mark = _landed((landed or {}).get(item.id)) or ""
            text, was_cut = _fill(_cell(item, leases, stale, (landed or {}).get(item.id)),
                                  widths[2])
            cut_any = cut_any or was_cut
            cells = [[_GLYPH.get(item.status, " ")], [str(item.id)], text]
            if landed_col:
                cells.append(_fill(["mixed" if ":" in mark else mark], widths[3])[0])
            rows.append(cells)
        header = ["", "id", "idea" if title == "Up next" else "epoch"]
        header += ["landed"] if landed_col else []
        out += _table([[h] for h in header], rows, widths, right={1})
        if hidden:
            out.append(f"  {hidden} older — clarity-ctl status --all --limit 0")
        out.append("")

    return out, cut_any


def view_text(items: list[Item], titles: list[str], leases: dict | None = None,
              stale: dict | None = None, landed: dict | None = None) -> str:
    """`show active|next|closed|all`: status's tables for just those groups, uncut by count."""
    lines, cut = _groups(items, [(t, GROUPS[t]) for t in titles], width(), leases, stale,
                         landed, oldest_first=False, limit=0)
    if cut:
        lines.append("… cut to a line — clarity-ctl show <id> for the whole of it")
    return "\n".join(lines).rstrip() + "\n"


def item_text(data: dict, marks: dict | None = None) -> str:
    """`show <id>`: one item as a card. Nothing is cut here — this is where the
    whole of a name, an outcome and every note is read."""
    cols = width()
    widths = [16, 0]
    widths[1] = cols - sum(widths) - 7
    w = widths[1]

    def wrap(text: str) -> list[str]:
        return textwrap.wrap(text, width=w, break_on_hyphens=False) or [""]

    fields: list[tuple[str, str]] = [("status", data["status"]), ("type", data.get("type", ""))]
    mark = _landed(marks)
    if mark:
        fields.append(("landed", mark))
    for key in ("outcome", "folder", "branch", "evidence"):
        if data.get(key):
            fields.append((key, data[key]))
    for git in data.get("git") or []:
        facts = [f"base {git['base']}" if git.get("base") else "no base"]
        if git.get("behind") or git.get("ahead"):
            facts.append(f"{git.get('ahead', 0)} ahead, {git.get('behind', 0)} behind")
        if git.get("dirty"):
            facts.append(f"{git['dirty']} uncommitted")
        if git.get("shared"):
            facts.append("shares the main checkout")
        fields.append(("repo", f"{git['repo']} — {', '.join(facts)}"))
    if not data.get("git"):
        fields += [("repo", r) for r in data.get("repos") or []]
    held = data.get("lease")
    if held:
        fields.append(("lease", f"{held.get('owner', '?')}@{held.get('host', '?')}, "
                                f"{held.get('age', '?')}"))
    fields += [("plan", p) for p in data.get("plans") or []]
    dates = [f"{k} {data[k]}" for k in ("created", "started", "ended") if data.get(k)]
    if dates:
        fields.append(("dates", " · ".join(dates)))

    rows = [[[key], wrap(value)] for key, value in fields]
    breaks = {0}  # fields read as one block; each note is its own row
    for note in data.get("notes") or []:
        breaks.add(len(rows))
        rows.append([[note["at"][:16]], wrap(note["text"])])
    head = [[f"{_GLYPH.get(data['status'], ' ')} {data['id']}"], wrap(data["name"])]
    return "\n".join(_table(head, rows, widths, breaks=breaks)) + "\n"


def status_text(objectives: Objectives, items: list[Item], show_all: bool = False,
                leases: dict | None = None, branches: bool = True,
                stale: dict | None = None, landed: dict | None = None,
                oldest_first: bool = False, limit: int = CLOSED_LIMIT) -> str:
    """The one-screen view. Printed, never written down — see the module docstring."""
    cols = width()
    out = []
    for label, text in (("OBJECTIVE", objectives.overall),):
        out += _wrap(text or "— not set —", f"{label:<11}", " " * 11, cols)
    out.append("")
    # One order for every group, named, so nobody has to remember which way a group
    # runs: newest first by default — recent work is what you look for — and oldest
    # first on request, when the finished work should read as a story.
    titles = ["Active", "Up next"] + (["Closed", "Dropped"] if show_all else [])
    groups = [(t, GROUPS[t]) for t in titles]

    lines, cut_any = _groups(items, groups, cols, leases, stale, landed, oldest_first, limit)
    out += lines
    if cut_any:
        out.append("… cut to a line — clarity-ctl show <id> for the whole of it")
    if not show_all:
        closed = len([i for i in items if i.status in CLOSED])
        out.append(f"{closed} closed or dropped — clarity-ctl status --all")
    if not branches:
        out.append("no repo for epochs to branch — they get a folder, but no branch or "
                   "worktree")
    return "\n".join(out).rstrip() + "\n"


def epoch_md(item: Item, existing: str | None = None) -> str:
    """Generated block on top; anything the human wrote below is preserved.

    Deliberately does not index PLANS/. That directory is one anyone can drop a file
    into, so no command can know when it changed — caching the listing here is what
    forced every epoch to be re-rendered on every write. `clarity-ctl show <id>` lists it live.
    """
    lines = [
        MARK,
        f"# {item.id:03d} · {item.name}",
        "",
        f"- **type** {item.type}",
        f"- **status** {item.status}",
    ]
    if item.branch:
        lines.append(f"- **branch** {item.branch}")
    if item.repos:
        lines.append(f"- **repos** {', '.join(item.repos)}")
    if item.bases:
        shown = sorted(set(item.bases.values()))
        lines.append(f"- **base** {shown[0]}" if len(shown) == 1 else
                     f"- **bases** {', '.join(f'{k}: {v}' for k, v in item.bases.items())}")
    if item.description:
        lines.append(f"- **goal** {item.description}")
    if item.outcome:
        lines.append(f"- **outcome** {item.outcome}")
    lines.append(f"- **started** {item.started or '—'}    **ended** {item.ended or '—'}")

    if item.notes:
        lines += ["", "## Tried"]
        lines += [f"- `{n.at.split()[0]}` {n.text}" for n in item.notes]
    lines += ["", EPOCH_MARK_END, ""]
    generated = "\n".join(lines)

    tail = ""
    if existing and EPOCH_MARK_END in existing:
        tail = existing.split(EPOCH_MARK_END, 1)[1].lstrip("\n")
    return generated + tail
