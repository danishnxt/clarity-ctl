"""Generated views: EPOCH.md and the terminal status block.

Nothing here reads state from disk; it is handed model objects and returns text.

There is deliberately no STATUS.md renderer. The status view mixes the worklog with
leases and git ahead/behind — machine-local facts that change with no command running
— so a committed file could only ever be wrong about them. `clarity-ctl status` composes
it on every run instead, which is the one place all three inputs are live.

`state_digest` is the exception that proves it: the worklog part alone, no leases and
no git, written into the agent block on every write. Everything in it changes only
when a command runs, so it cannot go stale — and an agent gets it with zero tool
calls, where every `clarity-ctl` call is a turn that re-reads the whole context.
"""

from __future__ import annotations

import os
import re
import shutil
import sys
import textwrap
import unicodedata
from datetime import datetime

from .model import CLOSED, DECISION, FUTURE, IN_FLIGHT, Item, Objectives, id_key

# Wrapped here, not by the terminal, so zooming or resizing never re-flows the output.
# Capped rather than fixed: a terminal narrower than the cap would wrap it again itself,
# which is the ugliness we're avoiding. Piped output ignores the terminal entirely.
MAX_WIDTH = 120
# Closed and Dropped show this many of their most recent; the rest are a flag away.
# The outcome is the point of a closed row, so the list is cut rather than the rows.
CLOSED_LIMIT = 15


def width() -> int:
    if not sys.stdout.isatty():
        return MAX_WIDTH  # stable for files and pipes
    return max(48, min(MAX_WIDTH, shutil.get_terminal_size((MAX_WIDTH, 24)).columns - 1))


def color() -> bool:
    """Color only for a person at a terminal. NO_COLOR (no-color.org) and TERM=dumb
    turn it off; FORCE_COLOR turns it on for a pager that understands it."""
    if os.environ.get("NO_COLOR") or os.environ.get("TERM") == "dumb":
        return False
    return bool(os.environ.get("FORCE_COLOR")) or sys.stdout.isatty()


_SGR = {"bold": "1", "dim": "2", "red": "31", "green": "32", "yellow": "33", "cyan": "36"}
_ANSI = re.compile(r"\x1b\[[0-9;]*m")


def paint(text: str, style: str | None) -> str:
    """`text` in `style` ("bold", "dim green", ...) — or as it is, without color.

    Applied after wrapping, never before: textwrap would count the escape codes."""
    if not style or not text or not color():
        return text
    codes = ";".join(_SGR[s] for s in style.split())
    return f"\x1b[{codes}m{text}\x1b[0m"


MARK = "<!-- GENERATED by clarity — edit config.yaml or use clarity commands -->"
EPOCH_MARK_END = "<!-- /GENERATED — write your own notes below this line -->"

# Single-width glyphs on purpose: emoji are double-width in most terminals and would
# push every border after them out of true, differently per font.
_GLYPH = {
    "idea": "·",
    "active": "▸",
    "done": "✓",
    "dropped": "✗",
}
_GLYPH_STYLE = {"idea": "dim", "active": "cyan", "done": "green", "dropped": "red"}


def _wrap(text: str, first: str, rest: str, cols: int) -> list[str]:
    return textwrap.wrap(text, width=cols, initial_indent=first, subsequent_indent=rest,
                         break_long_words=False, break_on_hyphens=False) or [first.rstrip()]



def note_age(item: Item) -> str | None:
    """How long the record has been standing still, for an epoch in flight.

    This exists because of a real failure: a session reversed the scope of its own
    epoch, tested it, had the result reviewed and rewrote it three times without
    writing one note, because every turn felt mid-task and a note was never the
    thing just asked for. Nothing in the view said so. Now it does — `status` is
    what an agent reads first, so it is where the nag belongs.
    """
    if item.status not in IN_FLIGHT or not item.notes:
        return None
    latest = max(n.at for n in item.notes)
    try:
        when = datetime.fromisoformat(latest)
    except ValueError:
        return None
    # A pre-timestamp note is a bare date, which parses as midnight — so its age
    # is coarse rather than absent. Better a day-granular nag on an old worklog
    # than silence on exactly the projects most likely to have gone quiet.
    minutes = int((datetime.now() - when).total_seconds() // 60)
    if minutes < 90:
        return None          # still warm; saying anything here is just noise
    if minutes < 60 * 24:
        return f"last note {minutes // 60}h ago"
    return f"last note {minutes // 1440}d ago"


def _landed(marks: dict[str, str] | None) -> str | None:
    """One word when every repo agrees, else one per repo — never a summary that hides a repo.

    unknown is left to --json: on an old worklog it marks nearly every early epoch,
    and a mark on everything is a mark on nothing."""
    marks = {repo: m for repo, m in (marks or {}).items() if m != "unknown"}
    if not marks:
        return None
    words = {"merged": "✅ merged", "unmerged": "❌ not merged"}
    if len(set(marks.values())) == 1:
        return words[next(iter(marks.values()))]
    return ", ".join(f"{repo}: {words[m]}" for repo, m in marks.items())


def _cell(item: Item, leases: dict | None, stale: dict | None,
          marks: dict | None, kids: list[Item] | None = None,
          expanded: bool = False) -> list[tuple[str, str | None, bool]]:
    """What goes in an item's main cell: (text, style, one line?) per paragraph —
    name, then detail.

    Name and outcome are cut to one line, because an old sentence-length name
    would otherwise make every row a paragraph. Nothing you act on — folder,
    lease, warnings — is ever cut. `show <id>` has the whole text.
    """
    paras = [(item.name, None, True)]
    if item.status in CLOSED and item.outcome:
        paras.append((f"outcome: {item.outcome}", "dim", True))
    elif item.folder:
        paras.append((item.folder, "dim", False))
    if expanded and item.parent is not None:
        paras.append((f"subepoch of {item.parent}", "dim", False))
    if kids and item.status in IN_FLIGHT and not expanded:
        # while an epoch's subepochs run, they are what you are watching: one line each,
        # cut like a name. Once it closes, a count is all the table needs.
        for kid in kids:
            line = f"↳ #{kid.id} {_GLYPH.get(kid.status, ' ')} {kid.name}"
            paras.append((line, "dim" if kid.status in CLOSED else None, True))
    elif kids:
        active = len([c for c in kids if c.status in IN_FLIGHT])
        closed = len([c for c in kids if c.status in CLOSED])
        noun = "subepoch" if len(kids) == 1 else "subepochs"
        paras.append((f"{len(kids)} {noun}: {active} active, {closed} closed", "dim", False))
    mark = _landed(marks)
    if item.status in CLOSED and mark and ":" in mark:
        # the column says "mixed"; this says which
        paras.append((f"landed: {mark}", "yellow", False))
    quiet = note_age(item)
    if quiet:
        # about the record, not about where the work lives — so not on the folder line
        paras.append((f"⚠ {quiet} — clarity-ctl note {item.id} \"...\"", "yellow", False))
    if item.status in IN_FLIGHT and marks and set(marks.values()) == {"merged"}:
        # only this one: unmerged is every epoch in flight, so saying it is noise
        paras.append((f"✓ its work is in its base — clarity-ctl epoch close {item.id} \"...\"",
                      "green", False))
    for trail in (stale or {}).get(item.id, []):
        # the base moving under an epoch is the thing you want to notice
        paras.append((f"⚠ {trail}", "yellow", False))
    return paras


def _dw(text: str) -> int:
    """Columns `text` takes in a terminal: an emoji or CJK character takes two.

    len() counts it as one, which is how a ✅ pushes every border after it out.
    Color codes take none."""
    text = _ANSI.sub("", text)
    return sum(0 if unicodedata.combining(c) or c == "\ufe0f" else
               2 if unicodedata.east_asian_width(c) in "WF" else 1 for c in text)


def _table(header: list[list[str]], rows: list[list[list[str]]], widths: list[int],
           right: set[int] = frozenset(), breaks: set[int] | None = None) -> list[str]:
    """Boxed rows, every cell already wrapped to its width; a rule before each row,
    or only before the rows in `breaks`.

    Hand-rolled rather than a library: the rest of status wraps by hand already,
    and a dependency for some box-drawing is weight every install would carry.
    """
    # borders dim: they are structure, and should sit behind what they hold
    bar = paint("│", "dim")

    def rule(left: str, mid: str, end: str) -> str:
        return paint(left + mid.join("─" * (w + 2) for w in widths) + end, "dim")

    def row(cells: list[list[str]]) -> list[str]:
        out = []
        for k in range(max(len(c) for c in cells)):
            parts = []
            for col, (cell, w) in enumerate(zip(cells, widths)):
                text = cell[k] if k < len(cell) else ""
                pad = " " * max(0, w - _dw(text))
                parts.append(f" {pad}{text} " if col in right else f" {text}{pad} ")
            out.append(bar + bar.join(parts) + bar)
        return out

    out = [rule("┌", "┬", "┐"), *row(header)]
    for n, cells in enumerate(rows):
        if breaks is None or n in breaks:
            out.append(rule("├", "┼", "┤"))
        out += row(cells)
    return out + [rule("└", "┴", "┘")]


def _fill(paras: list[tuple[str, str | None, bool]], w: int) -> tuple[list[str], bool]:
    """Wrapped to the cell, then painted; True if a one-line paragraph had to be cut."""
    out, cut = [], False
    for text, style, one in paras:
        # long words break too: a path wider than the cell would push the border out
        lines = textwrap.wrap(text, width=w, break_on_hyphens=False) or [""]
        if one and len(lines) > 1:
            first = lines[0]
            if len(first) > w - 2:
                first = first[:w - 2].rsplit(" ", 1)[0] if " " in first[:w - 2] else first[:w - 2]
            lines, cut = [first + " …"], True
        out += [paint(line, style) for line in lines]
    return out, cut


CUT_HINT = "… cut to a line — clarity-ctl show <id> for the whole of it"

GROUPS = {
    "Active": IN_FLIGHT,
    "Up next": FUTURE,
    # Closed is what you finished; dropped work gets its own group, so scanning
    # what shipped is never interleaved with what you gave up on.
    "Closed": {"done"},
    "Dropped": {"dropped"},
}


def _groups(items: list[Item], groups: list[tuple[str, set]], cols: int,
            leases: dict | None, stale: dict | None, landed: dict | None,
            oldest_first: bool, limit: int, kids: dict | None = None,
            children: bool = False) -> tuple[list[str], bool]:
    """One titled table per group. True as well if any name or outcome was cut.

    Subepochs are left out of the tables unless `children` asks for them: they are
    listed or counted on their parent's row, so ten running agents do not bury it.
    """
    out: list[str] = []
    cut_any = False
    for title, statuses in groups:
        chosen = [i for i in items if i.status in statuses and (children or i.parent is None)]
        # closed_seq is exact where it exists; a project that predates it falls back to
        # the date, which is how these read before, so old worklogs keep their order.
        chosen.sort(key=lambda i: (i.closed_seq or 0, i.ended or i.created or "", id_key(i.id)),
                    reverse=True)
        total, hidden = len(chosen), 0
        if statuses <= CLOSED and limit > 0 and len(chosen) > limit:
            # the most recent, whichever way they are then read
            hidden = len(chosen) - limit
            chosen = chosen[:limit]
        if oldest_first:
            chosen.reverse()
        # the whole count, even when the list is cut
        out.append(f"{paint(title, 'bold')} {paint(f'({total})', 'dim')}")
        if not chosen:
            out += ["  —", ""]
            continue
        # landed only where something can have landed: a closed epoch's work
        landed_col = title == "Closed"
        # wide enough for its widest value in terminal columns: "❌ not merged" is 13
        # no status symbol column: every row in a group shares its status, and the
        # heading already says it
        widths = [3, 0] + ([_dw("❌ not merged")] if landed_col else [])
        widths[1] = cols - sum(widths) - 3 * len(widths) - 1  # borders and padding
        rows = []
        for item in chosen:
            mark = _landed((landed or {}).get(item.id)) or ""
            text, was_cut = _fill(_cell(item, leases, stale, (landed or {}).get(item.id),
                                        kids=(kids or {}).get(item.id), expanded=children),
                                  widths[1])
            cut_any = cut_any or was_cut
            cells = [[str(item.id)], text]
            if landed_col:
                style = ("yellow" if ":" in mark else
                         "green" if "not" not in mark else "red")
                cells.append(_fill([("mixed" if ":" in mark else mark, style, False)],
                                   widths[2])[0])
            rows.append(cells)
        header = ["id", "idea" if title == "Up next" else "epoch"]
        header += ["landed"] if landed_col else []
        out += _table([[paint(h, "dim")] for h in header], rows, widths, right={0})
        if hidden:
            out.append(paint(f"  {hidden} older — clarity-ctl status --all --limit 0", "dim"))
        out.append("")

    return out, cut_any


def view_text(items: list[Item], titles: list[str], leases: dict | None = None,
              stale: dict | None = None, landed: dict | None = None,
              kids: dict | None = None, children: bool = False) -> str:
    """`show active|next|closed|all`: status's tables for just those groups, uncut by count."""
    lines, cut = _groups(items, [(t, GROUPS[t]) for t in titles], width(), leases, stale,
                         landed, oldest_first=False, limit=0, kids=kids, children=children)
    if cut:
        lines.append(paint(CUT_HINT, "dim"))
    return "\n".join(lines).rstrip() + "\n"


def _ago(at: str, now: datetime | None = None) -> str:
    """'just now', '14h ago', '3d ago' — or the date, past a month. A bare date
    (no time of day) is only ever day-granular: 'today', 'yesterday', '3d ago'."""
    now = now or datetime.now()
    try:
        when = datetime.fromisoformat(at)
    except ValueError:
        return at
    if len(at) <= 10:
        days = (now.date() - when.date()).days
        return "today" if days <= 0 else "yesterday" if days == 1 else (
            f"{days}d ago" if days < 31 else at)
    minutes = int((now - when).total_seconds() // 60)
    if minutes < 2:
        return "just now"
    if minutes < 60:
        return f"{minutes}m ago"
    if minutes < 60 * 24:
        return f"{minutes // 60}h ago"
    return f"{minutes // 1440}d ago" if minutes < 60 * 24 * 31 else at[:10]


_POINT = re.compile(r"\((\d+)\)\s+")


def note_points(text: str) -> list[str]:
    """A note's text split at its own numbering — `(1) … (2) … (3) …` — so show can
    put each point on a line of its own. Only a run counting up from 1 counts, so a
    stray "(3)" in prose stays where it is. No run, one piece: the text as written."""
    cuts, want = [], 1
    for m in _POINT.finditer(text):
        if int(m.group(1)) == want:
            cuts.append(m.start())
            want += 1
    if len(cuts) < 2:
        return [text]
    pieces = [text[:cuts[0]]] + [text[a:b] for a, b in zip(cuts, cuts[1:] + [len(text)])]
    return [p.strip() for p in pieces if p.strip()]


def item_text(data: dict, marks: dict | None = None) -> str:
    """`show <id>`: one item as a page, the way gh issue view and brew info read.

    A bold title, one dim line of status, the outcome as prose, then sections. No
    box: borders are for lists, where they keep rows apart. Nothing is cut here —
    this is where the whole of a name, an outcome and every note is read."""
    # prose reads best short of the full terminal; gh and man pages stop near here too
    cols = min(width(), 100)
    status = data["status"]

    def para(text: str, indent: int, style: str | None = None) -> list[str]:
        lines = textwrap.wrap(text, width=cols - indent, break_on_hyphens=False) or [""]
        return [" " * indent + paint(line, style) for line in lines]

    def section(title: str) -> list[str]:
        return ["", f"{paint('==>', 'cyan bold')} {paint(title, 'bold')}"]

    # title, with the id after it on the last line — the id is what you type next
    title = textwrap.wrap(data["name"], width=cols - len(f"  #{data['id']}"),
                          break_on_hyphens=False) or [""]
    out = [paint(line, "bold") for line in title]
    out[-1] += "  " + paint(f"#{data['id']}", "dim")

    facts = [paint(f"{_GLYPH.get(status, ' ')} {status}", _GLYPH_STYLE.get(status))]
    mark = _landed(marks)
    if mark:
        bases = sorted(set((data.get("bases") or {}).values()))
        into = f" into {bases[0]}" if len(bases) == 1 and ":" not in mark else ""
        facts.append(paint(mark + into, "yellow" if ":" in mark else
                           "red" if "not" in mark else "green"))
    facts.append(paint(data.get("type", ""), "dim"))
    if data.get("archived"):
        facts.append(paint(f"archived in {data['archived']} (read-only)", "dim"))
    if data.get("parent") is not None:
        facts.append(paint(f"subepoch of {data['parent']}", "dim"))
    if data.get("ended"):
        when = f"closed {_ago(data['ended'])}"
    elif data.get("started"):
        when = f"started {_ago(data['started'])}"
    else:
        when = f"added {_ago(data.get('created', ''))}"
    facts.append(paint(when, "dim"))
    out.append(paint(" • ", "dim").join(facts))

    if data.get("outcome"):
        out += [""] + para(data["outcome"], 2)

    if data.get("brief"):
        out += section("Brief")
        out += para(data["brief"], 2)

    where: list[tuple[str, str]] = []
    if data.get("branch"):
        where.append(("branch", data["branch"]))
    if data.get("folder"):
        where.append(("folder", data["folder"]))
    for git in data.get("git") or []:
        facts = [f"base {git['base']}" if git.get("base") else "no base"]
        # ahead/behind only while the branch is live: after a close, main moving
        # on makes "N behind" true and useless — landed says what matters then
        if status not in CLOSED and (git.get("behind") or git.get("ahead")):
            facts.append(f"{git.get('ahead', 0)} ahead, {git.get('behind', 0)} behind")
        if git.get("dirty"):
            facts.append(f"{git['dirty']} uncommitted")
        elif git.get("dirty_error"):
            facts.append(f"uncommitted unknown — git status failed: {git['dirty_error']}")
        if git.get("shared"):
            facts.append("shares the main checkout")
        where.append(("repo", f"{git['repo']} — {', '.join(facts)}"))
    if not data.get("git"):
        where += [("repo", r) for r in data.get("repos") or []]
    where += [("plan", p) for p in data.get("plans") or []]
    if data.get("evidence"):
        where.append(("from", data["evidence"]))
    if where:
        out += section("Where")
        key_w = max(len(k) for k, _ in where) + 2
        for key, value in where:
            lines = textwrap.wrap(value, width=cols - 2 - key_w, break_on_hyphens=False)
            out.append("  " + paint(f"{key:<{key_w}}", "dim") + (lines or [""])[0])
            out += [" " * (2 + key_w) + line for line in lines[1:]]

    kids = data.get("children") or []
    if kids:
        out += section(f"Subepochs ({len(kids)})")
        for kid in kids:
            glyph = paint(f"{_GLYPH.get(kid['status'], ' ')} {kid['status']}",
                          _GLYPH_STYLE.get(kid["status"]))
            out.append(f"  #{kid['id']} {kid['name']} — {glyph}")
            # a finished child is summed up by its outcome; one still going, by its handoff
            if kid["status"] in CLOSED and kid.get("outcome"):
                out += para(f"outcome: {kid['outcome']}", 4, "dim")
            elif kid.get("handoff"):
                out += para(f"handoff: {kid['handoff']}", 4, "dim")

    notes = data.get("notes") or []
    if notes:
        out += section(f"Notes ({len(notes)})")
        for n, note in enumerate(notes, 1):
            out += ["", "  " + paint(f"{n}.", "bold") + " "
                    + paint(f"{_ago(note['at'])} · {note['at'][:16]}", "dim")]
            for k, point in enumerate(note_points(note["text"])):
                if k:
                    out.append("")
                if _POINT.match(point):
                    # the number hangs; the point's own lines line up after it
                    num = _POINT.match(point).group(0)
                    body = textwrap.wrap(point[len(num):], width=cols - 4 - len(num),
                                         break_on_hyphens=False) or [""]
                    out += ["    " + num + body[0], *("    " + " " * len(num) + b
                                                     for b in body[1:])]
                else:
                    out += para(point, 4)
    return "\n".join(out) + "\n"


def status_text(objectives: Objectives, items: list[Item], show_all: bool = False,
                leases: dict | None = None, branches: bool = True,
                stale: dict | None = None, landed: dict | None = None,
                oldest_first: bool = False, limit: int = CLOSED_LIMIT,
                kids: dict | None = None, children: bool = False) -> str:
    """The one-screen view. Printed, never written down — see the module docstring."""
    cols = width()
    out = []
    lines = _wrap(objectives.overall or "— not set —", " " * 11, " " * 11, cols)
    out += [paint("OBJECTIVE", "bold") + lines[0][9:], *lines[1:]]
    out.append("")
    # One order for every group, named, so nobody has to remember which way a group
    # runs: newest first by default — recent work is what you look for — and oldest
    # first on request, when the finished work should read as a story.
    titles = ["Active", "Up next"] + (["Closed", "Dropped"] if show_all else [])
    groups = [(t, GROUPS[t]) for t in titles]

    lines, cut_any = _groups(items, groups, cols, leases, stale, landed, oldest_first, limit,
                             kids=kids, children=children)
    out += lines
    if cut_any:
        out.append(paint(CUT_HINT, "dim"))
    if not show_all:
        closed = len([i for i in items if i.status in CLOSED])
        out.append(paint(f"{closed} closed or dropped — clarity-ctl status --all", "dim"))
    if not branches:
        out.append(paint("no repo for epochs to branch — they get a folder, but no branch "
                         "or worktree", "dim"))
    return "\n".join(out).rstrip() + "\n"


# How much of the history the digest carries. Bounded, so a project's thousandth
# epoch costs every session no more than its tenth; the rest is a command away.
DIGEST_CLOSED = 10
DIGEST_IDEAS = 12
DIGEST_DECISIONS = 20
DIGEST_TEXT = 240  # characters of any one note, brief or outcome
DIGEST_HANDOFF = 600  # a handoff gets more: it is the line the next session acts on
DIGEST_NAME = 80  # a name is a title; one written as a paragraph is cut, not carried whole


def _line(text: str, limit: int = DIGEST_TEXT) -> str:
    text = " ".join(text.split())
    return text if len(text) <= limit else text[:limit - 1].rstrip() + "…"


def state_digest(objectives: Objectives, items: list[Item]) -> str:
    """Where things stand, as markdown for the agent block: the worklog's part of
    status, plus what status leaves to `show` — handoffs and standing decisions.

    `items` should be live and archived together: a decision does not stop standing
    because its epoch was archived.
    """
    def finished_order(i: Item):
        return (i.closed_seq or 0, i.ended or i.created or "", id_key(i.id))

    out = ["### Where things stand", "",
           "Generated from the worklog on every clarity write, so it is current. "
           "`clarity-ctl status` adds branches and leases; `clarity-ctl show <id>` has every note.", "",
           f"**Objective:** {_line(objectives.overall or '— not set —')}", "", "**Active**"]

    active = sorted((i for i in items if i.status in IN_FLIGHT), key=lambda i: id_key(i.id))
    for i in active:
        latest = next((n.text for n in reversed(i.notes) if not n.text.startswith(DECISION)), None)
        if i.handoff:
            what = f"handoff: {_line(i.handoff, DIGEST_HANDOFF)}"
        elif latest:
            what = f"last note: {_line(latest)}"
        else:
            what = f"brief: {_line(i.brief)}" if i.brief else "no notes yet"
        where = "".join(f" (work in `{i.folder}/wt/{r.rsplit('/', 1)[-1]}`)"
                        for r in (i.repos or []) if i.folder and i.branch)
        out.append(f"- #{i.id} {_line(i.name, DIGEST_NAME)}{where} — {what}")
    if not active:
        out.append("- none")

    ideas = sorted((i for i in items if i.status in FUTURE), key=lambda i: id_key(i.id))
    shown = " · ".join(f"#{i.id} {_line(i.name, DIGEST_NAME)}" for i in ideas[:DIGEST_IDEAS]) or "none"
    more = f" · {len(ideas) - DIGEST_IDEAS} more: `clarity-ctl show next`" if len(ideas) > DIGEST_IDEAS else ""
    out += ["", f"**Up next:** {shown}{more}"]

    decisions = sorted(((n, i) for i in items for n in i.decisions),
                       key=lambda d: d[0].at, reverse=True)
    if decisions:
        out += ["", "**Standing decisions**, newest first"]
        out += [f"- {_line(n.text[len(DECISION):].strip())} (#{i.id})"
                for n, i in decisions[:DIGEST_DECISIONS]]
        if len(decisions) > DIGEST_DECISIONS:
            out.append(f"- {len(decisions) - DIGEST_DECISIONS} older, in the notes of the epochs they name")

    closed = sorted((i for i in items if i.status in CLOSED), key=finished_order, reverse=True)
    if closed:
        out += ["", "**Recently closed**, newest first"]
        out += [f"- #{i.id} {'✓' if i.status == 'done' else '✗ dropped'} {_line(i.name, DIGEST_NAME)}"
                f"{' — ' + _line(i.outcome) if i.outcome else ''}" for i in closed[:DIGEST_CLOSED]]
        if len(closed) > DIGEST_CLOSED:
            out.append(f"- {len(closed) - DIGEST_CLOSED} older: `clarity-ctl status --all --limit 0`")
    return "\n".join(out)


def epoch_md(item: Item, existing: str | None = None) -> str:
    """Generated block on top; anything the human wrote below is preserved.

    Deliberately does not index PLANS/. That directory is one anyone can drop a file
    into, so no command can know when it changed — caching the listing here is what
    forced every epoch to be re-rendered on every write. `clarity-ctl show <id>` lists it live.
    """
    lines = [
        MARK,
        f"# {item.code} · {item.name}",
        "",
        f"- **type** {item.type}",
        f"- **status** {item.status}",
    ]
    if item.branch:
        lines.append(f"- **branch** {item.branch}")
    if item.repos:
        lines.append(f"- **repos** {', '.join(item.repos)}")
    if item.bases:
        shown = sorted(set(item.bases.values()))
        lines.append(f"- **base** {shown[0]}" if len(shown) == 1 else
                     f"- **bases** {', '.join(f'{k}: {v}' for k, v in item.bases.items())}")
    if item.description:
        lines.append(f"- **goal** {item.description}")
    if item.outcome:
        lines.append(f"- **outcome** {item.outcome}")
    lines.append(f"- **started** {item.started or '—'}    **ended** {item.ended or '—'}")

    if item.notes:
        lines += ["", "## Tried"]
        lines += [f"- `{n.at.split()[0]}` {n.text}" for n in item.notes]
    lines += ["", EPOCH_MARK_END, ""]
    generated = "\n".join(lines)

    tail = ""
    if existing and EPOCH_MARK_END in existing:
        tail = existing.split(EPOCH_MARK_END, 1)[1].lstrip("\n")
    return generated + tail
